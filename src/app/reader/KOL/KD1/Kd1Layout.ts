/**
 * KD1 (1997 年の第 2-2 版) のレコードの項目を、KD2/KD3 のレコードのどこに置くか。
 * [KD1 のアドレス, 桁数, KD2 のアドレス] の並びで、アドレスは 0 始まり。
 *
 * KD1 は項目の意味が KD2 と同じで、項目の並びだけが違う。
 * KD1 のレコードを KD2 の並びのレコードに組み替えて、KD2 の取り込み処理に渡す。
 * KD1 にない項目は、空白のままになる。
 */
